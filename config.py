# Yahoo 已無現貨 XAU/USD（XAUUSD=X 回 404），期貨連續月是可取得的最佳代理。
#
# 已知限制（誠實揭露）：GC=F 用 COMEX 下午 1:30 (ET) 結算，而 DXY / SP500 / VIX
# 是下午 4:00 收盤，兩者相差 2.5 小時，日報酬相關性因此略降。這是換用真實金價
# 必須接受的取捨。

