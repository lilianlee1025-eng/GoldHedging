# 取捨：第一次重訓的樣本數較少（約 685 條序列），初期訊號品質會比後期弱一些。
WF_INITIAL_TRAIN = 750
WF_STEP = 60              # 每次往前滾動的步長（每 60 個交易日重訓一次）
WF_EPOCHS = 20            # 回測時為了速度，epoch 少一點

# 避險策略：依「下跌機率」決定避險力道（0~1）
# 當模型預測下跌機率高 → 提高避險比例，降低金價曝險
HEDGE_PROB_THRESHOLD = 0.5   # 機率超過此值才開始避險
